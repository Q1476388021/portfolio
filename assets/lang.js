let currentLang = 'zh';

function setLanguage(lang) {
    currentLang = lang;
    localStorage.setItem('portfolio-lang', lang);
    
    document.querySelectorAll('[data-lang-key]').forEach(element => {
        const key = element.getAttribute('data-lang-key');
        if (translations[key] && translations[key][lang]) {
            element.innerHTML = translations[key][lang];
        }
    });
    
    const langTrack = document.getElementById('lang-track');
    if (langTrack) {
        if (lang === 'en') {
            langTrack.classList.add('active');
        } else {
            langTrack.classList.remove('active');
        }
    }
    
    updateDynamicValues(lang);
}

function updateDynamicValues(lang) {
    const ageEl = document.getElementById('age-value');
    const experienceEl = document.getElementById('experience-value');
    
    if (ageEl) {
        const ageMatch = ageEl.textContent.match(/(\d+)/);
        if (ageMatch) {
            ageEl.textContent = lang === 'zh' ? ageMatch[1] + '岁' : ageMatch[1] + ' years';
        }
    }
    
    if (experienceEl) {
        const expMatch = experienceEl.textContent.match(/(\d+)/);
        if (expMatch) {
            experienceEl.textContent = lang === 'zh' ? expMatch[1] + '年+' : expMatch[1] + '+ years';
        }
    }
}

function toggleLanguage() {
    const newLang = currentLang === 'zh' ? 'en' : 'zh';
    setLanguage(newLang);
}

document.addEventListener('DOMContentLoaded', function() {
    const savedLang = localStorage.getItem('portfolio-lang') || 'zh';
    setLanguage(savedLang);
    
    const langSwitch = document.querySelector('.lang-switch');
    if (langSwitch) {
        langSwitch.addEventListener('click', toggleLanguage);
    }
});